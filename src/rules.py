LEXICONS: Dict[str, List[str]] = {
    "bad_pos": BAD_POSITIVE,
    "bad_neg": BAD_NEGATIVE,
    "flam_pos": FLAM_POSITIVE,
    "flam_neg": FLAM_NEGATIVE,
}

FEATURE_NAMES = [
    "bad_pos_hits", "bad_neg_hits", "flam_pos_hits", "flam_neg_hits",
    "bad_pos_uniq", "bad_neg_uniq", "flam_pos_uniq", "flam_neg_uniq",
    "text_len_log", "has_description", "n_images",
]


def _count_hits(text_low: str, lexicon: List[str]):
    total, uniq = 0, 0
    for term in lexicon:
        c = text_low.count(term)
        if c:
            uniq += 1
            total += c
    return total, uniq


def extract_rule_features(df: pd.DataFrame, text_col: str = "text") -> np.ndarray:
    """Матрица правиловых признаков (n, len(FEATURE_NAMES))."""
    feats = np.zeros((len(df), len(FEATURE_NAMES)), dtype=np.float32)
    texts = df[text_col].fillna("").astype(str).str.lower().tolist()
    n_images = df["image_paths"].apply(len).values if "image_paths" in df else np.zeros(len(df))
    has_desc = df["description"].notna().values if "description" in df else np.ones(len(df))

    for i, t in enumerate(texts):
        col = 0
        uniq_vals = []
        for key in ("bad_pos", "bad_neg", "flam_pos", "flam_neg"):
            total, uniq = _count_hits(t, LEXICONS[key])
            feats[i, col] = min(total, 20)
            uniq_vals.append(min(uniq, 10))
            col += 1
        feats[i, 4:8] = uniq_vals
        feats[i, 8] = math.log1p(len(t))
        feats[i, 9] = float(has_desc[i])
        feats[i, 10] = min(float(n_images[i]), 5.0)
    return feats


def rule_prob_ok(df: pd.DataFrame, feats: np.ndarray = None) -> np.ndarray:
    """Грубая P(label=1 | правила) для холодного старта и как фича стекинга.

    Направление сверено с трейном (AUC по label): в ОБЕИХ категориях товары
    с явными маркировками своей категории чаще «не бан» — баны это карточки
    БЕЗ обязательных маркировок (БАД AUC 0.75, ЛВЖ 0.56 при этом знаке).
    """
    if feats is None:
        feats = extract_rule_features(df)
    probs = np.full(len(df), 0.5, dtype=np.float32)
    cats = df["category"].values
    for i in range(len(df)):
        if cats[i] == CAT_BAD:
            raw = feats[i, 4] - 1.5 * feats[i, 5]      # uniq bad_pos - uniq bad_neg
        else:
            raw = feats[i, 6] - 1.5 * feats[i, 7]      # uniq flam_pos - uniq flam_neg
        probs[i] = 1.0 / (1.0 + math.exp(-0.6 * raw))  # P(ok): маркировки есть -> выше
    return probs


def rule_prob_ok_learned(df: pd.DataFrame, feats: np.ndarray = None) -> np.ndarray:
    """P(ok) обученной логрег-головой на правиловых признаках.

    Артефакты artifacts/rules_head_{bad,flam}.joblib создаёт
    train/train_cheap_heads.py; при их отсутствии — ручной сигмоид.
    """
    import joblib

    from src.config import ARTIFACTS_DIR
    if feats is None:
        feats = extract_rule_features(df)
    probs = rule_prob_ok(df, feats)                # фолбэк
    for cat, key in ((CAT_BAD, "bad"), (CAT_FLAM, "flam")):
        path = ARTIFACTS_DIR / f"rules_head_{key}.joblib"
        if not path.exists():
            continue
        head = joblib.load(path)
        mask = (df["category"] == cat).values
        if mask.any():
            p = head.predict_proba(feats[mask])[:, list(head.classes_).index(1)]
            probs[mask] = p.astype(np.float32)
    return probs


