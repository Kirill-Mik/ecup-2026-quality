"""Центральная конфигурация решения E-CUP 2026, задача 2 «Контроль качества».

Сознательно ВЫРЕЗАНО всё, что относилось к моделям из /shared_models
(Qwen-эмбеддинги, OCR, VLM-судья, LLM-комментарии): эти шаги невозможно
прогнать в домашней репетиции, а непроверенный шаг уже дважды обрушивал
сабмит (0.71 и 0.67 при домашней оценке 0.92). Правило проекта:
чего нет в репетиции — того нет и в сабмите.
"""
import os
from pathlib import Path

# ------------------------------------------------------------------ пути
ROOT = Path(__file__).resolve().parent.parent          # корень архива решения
ARTIFACTS_DIR = ROOT / "artifacts"                     # обученные модели/пороги

# ------------------------------------------------------------------ категории
CAT_BAD = "БАД"
CAT_FLAM = "Легковоспламеняющиеся"


def norm_category(raw: str) -> str:
    """Нормализация категории: терпим к регистру/пробелам/вариациям."""
    s = str(raw).strip().lower()
    if s.startswith("бад"):
        return CAT_BAD
    return CAT_FLAM


# ------------------------------------------------------------------ формат result
# label 1 = качественный = «не бан», label 0 = «бан» (сверено с baseline)
VERDICT_OK = "не бан"
VERDICT_BAN = "бан"
MIN_COMMENT_LEN = 50
MAX_COMMENT_LEN = 300
RESULT_TEMPLATE = "<комментарий>{comment}<вердикт>{verdict}"

# ------------------------------------------------------------------ тайм-бюджет
# Лимиты стадий: Check 3 мин / Public 20 мин / Private 40 мин.
# Стадию определяем эвристикой по числу строк теста (переопределяется env-ом).
SAFETY_FRACTION = 0.85          # используем максимум 85% лимита
WRITE_RESERVE_SEC = 60          # неприкосновенный резерв на запись/валидацию


def stage_time_limit(n_rows: int) -> int:
    env = os.environ.get("ECUP_TIME_LIMIT_SEC")
    if env:
        return int(env)
    if n_rows <= 300:
        return 3 * 60           # Check
    if n_rows <= 2500:
        return 20 * 60          # Public (~1600 товаров)
    return 40 * 60              # Private (~3800 товаров)


# ------------------------------------------------------------------ фолбэки
# Используются только если artifacts/blend.json почему-то не прочитался.
DEFAULT_THRESHOLDS = {CAT_BAD: 0.5, CAT_FLAM: 0.5}
